import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'

test('research discovers, confirms, exports, imports and replays real experiments',async({page})=>{
 test.setTimeout(90000)
 const external:string[]=[]
 page.on('request',request=>{if(!request.url().startsWith('http://127.0.0.1:5174/')&&!request.url().startsWith('data:'))external.push(request.url())})
 await page.goto('/')
 await page.getByRole('button',{name:'Research lab'}).click()
 await page.getByLabel('Research candidates').selectOption('4')
 await page.getByLabel('Research discovery seeds').selectOption('4')
 await page.getByLabel('Research confirmation seeds').selectOption('4')
 await page.getByLabel('Research duration').selectOption('20')
 await page.getByRole('button',{name:'START RESEARCH'}).click()
 await expect(page.getByRole('heading',{name:'Research complete'})).toBeVisible({timeout:60000})
 await expect(page.getByText('Independent confirmation',{exact:true})).toBeVisible()
 await expect(page.getByRole('group',{name:/Candidate configurations/})).toBeVisible()
 await page.getByRole('button',{name:'EXPLAIN THIS DISCOVERY'}).click()
 await expect(page.getByRole('dialog')).toContainText('simplified teaching simulation')
 await page.getByRole('button',{name:'Close research explanation'}).click()
 await page.getByRole('button',{name:'Explain Confirmation'}).first().click()
 await expect(page.getByRole('dialog')).toContainText('seeds that were not used')
 await page.getByRole('button',{name:'Close research explanation'}).click()
 const pending=page.waitForEvent('download')
 await page.getByRole('button',{name:'JSON',exact:true}).click()
 const data=JSON.parse(await readFile((await (await pending).path())!,'utf8'))
 expect(data.stage).toBe('complete')
 expect(data.model).toBe('coarse-grained-5')
 expect(data.config.base.targetMode).toBe(1)
 expect(data.candidates).toHaveLength(5)
 expect(data.discoverySeeds).toHaveLength(4)
 expect(data.confirmationSeeds).toHaveLength(4)
 expect(data.confirmationSeeds.every((seed:number)=>!data.discoverySeeds.includes(seed))).toBe(true)
 expect(data.winner).toBeTruthy()
 expect(data.completedTrials).toBe(data.totalTrials)
 expect(data.events.findIndex((e:{text:string})=>e.text.includes('Locked'))).toBeLessThan(data.events.findIndex((e:{text:string})=>e.text.includes('fresh matched')))
 const rows=data.candidates.flatMap((c:{trials:unknown[]})=>c.trials)
 expect(rows).toHaveLength(data.completedTrials)
 const reportPromise=page.waitForEvent('download')
 await page.getByRole('button',{name:'REPORT',exact:true}).click()
 const report=await readFile((await (await reportPromise).path())!,'utf8')
 expect(report).toContain('## Independent confirmation')
 expect(report).toContain('not physical molecular predictions')
 expect(report).toContain(`Selected: ${data.winner}`)
 const csvPromise=page.waitForEvent('download')
 await page.getByRole('button',{name:'CSV',exact:true}).click()
 const csv=await readFile((await (await csvPromise).path())!,'utf8')
 expect(csv.trim().split('\n')).toHaveLength(data.completedTrials+1)
 await page.getByLabel('Import research JSON').setInputFiles({name:'research.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(data))})
 await expect(page.getByText(/Research imported/)).toBeVisible()
 await page.getByRole('button',{name:'REPLAY THIS TRIAL'}).click()
 await expect(page.getByText(/Research trial loaded and paused/)).toBeVisible()
 await expect(page.getByRole('button',{name:'Play',exact:true})).toBeVisible()
 expect(external).toEqual([])
})

test('research pauses, restores after reload, resumes and cancels',async({page})=>{
 test.setTimeout(45000)
 await page.goto('/')
 await page.getByRole('button',{name:'Research lab'}).click()
 await page.getByLabel('Research candidates').selectOption('12')
 await page.getByLabel('Research discovery seeds').selectOption('40')
 await page.getByLabel('Research confirmation seeds').selectOption('40')
 await page.getByLabel('Research duration').selectOption('100')
 await page.getByRole('button',{name:'START RESEARCH'}).click()
 await expect(page.getByRole('button',{name:'PAUSE',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'PAUSE',exact:true}).click()
 await expect(page.getByRole('button',{name:'RESUME'})).toBeVisible()
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('matterforge-research-session-v1')||'null'))
 expect(saved.status).toBe('paused')
 await page.reload()
 await page.getByRole('button',{name:'Research lab'}).click()
 await expect(page.getByRole('button',{name:'RESUME'})).toBeVisible()
 await expect(page.getByText(/Recovered the latest saved checkpoint/)).toBeVisible()
 await page.getByRole('button',{name:'RESUME'}).click()
 await expect(page.getByRole('button',{name:'PAUSE',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'CANCEL',exact:true}).click()
 await expect(page.getByRole('button',{name:'RESUME'})).toHaveCount(0)
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('matterforge-research-session-v1')||'null')?.status)).toBe('cancelled')
})

