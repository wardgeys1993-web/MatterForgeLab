test('worker loading failure leaves a resumable local checkpoint',async({page})=>{
 await page.route(/research\.worker/,route=>route.abort())
 await page.goto('/')
 await page.getByRole('button',{name:'Research lab'}).click()
 await page.getByRole('button',{name:'START RESEARCH'}).click()
 await expect(page.getByText(/research worker stopped unexpectedly/)).toBeVisible({timeout:10000})
 await expect(page.getByRole('button',{name:'RESUME'})).toBeVisible()
 expect(await page.evaluate(()=>localStorage.getItem('matterforge-research-session-v1'))).not.toBeNull()
})

test('optional local AI uses a mocked local adapter and fails safely when disconnected',async({page})=>{
 test.setTimeout(60000)
 const endpoint='http://127.0.0.1:11434/v1/chat/completions'
 let calls=0
 await page.route(endpoint,route=>{if(route.request().method()==='OPTIONS')return route.fulfill({status:204,headers:{'access-control-allow-origin':'*','access-control-allow-methods':'POST, OPTIONS','access-control-allow-headers':'content-type'}});calls++;return route.fulfill({status:200,headers:{'access-control-allow-origin':'*','content-type':'application/json'},body:JSON.stringify({choices:[{message:{content:'Mock local explanation based on the supplied report.'}}]})})})
 await page.goto('/')
 await page.getByRole('button',{name:'Research lab'}).click()
 await page.getByLabel('Research candidates').selectOption('4')
 await page.getByLabel('Research discovery seeds').selectOption('4')
 await page.getByLabel('Research confirmation seeds').selectOption('4')
 await page.getByLabel('Research duration').selectOption('20')
 await page.getByRole('button',{name:'START RESEARCH'}).click()
 await expect(page.getByRole('heading',{name:'Research complete'})).toBeVisible({timeout:45000})
 const before=await page.evaluate(()=>localStorage.getItem('matterforge-research-session-v1'))
 await page.getByText('OPTIONAL LOCAL AI RESEARCHER').click()
 await page.getByLabel('Local AI model').fill('mock-model')
 await page.getByRole('button',{name:'ASK LOCAL AI TO EXPLAIN'}).click()
 await expect(page.getByText('Mock local explanation based on the supplied report.')).toBeVisible()
 expect(calls).toBe(1)
 expect(await page.evaluate(()=>localStorage.getItem('matterforge-research-session-v1'))).toBe(before)
 await page.unroute(endpoint)
 await page.route(endpoint,route=>route.abort())
 await page.getByRole('button',{name:'SUGGEST FOLLOW-UP IDEAS'}).click()
 await expect(page.getByText(/local server is unavailable/)).toBeVisible()
 expect(await page.evaluate(()=>localStorage.getItem('matterforge-research-session-v1'))).toBe(before)
})
