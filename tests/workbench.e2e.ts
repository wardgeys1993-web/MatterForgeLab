test('controlled study runs 100 matched seeds and exports real paired outcomes',async({page})=>{
 test.setTimeout(90000)
 await page.goto('/')
 await expect(page.getByText('v0.6.0')).toBeVisible()
 await page.getByRole('button',{name:'START MY FIRST EXPERIMENT'}).click()
 await page.getByRole('button',{name:'Pause',exact:true}).click()
 await page.getByRole('button',{name:'CONTROLLED STUDY'}).click()
 const lab=page.getByRole('region',{name:'Controlled experiment laboratory'})
 await expect(lab.getByLabel('Number of controlled seeds')).toHaveValue('100')
 await expect(lab.getByLabel('Starting arrangement')).toHaveValue('fixed')
 await expect(lab.getByLabel('Seed selection')).toHaveValue('random')
 await lab.getByLabel('Value A').fill('0.4')
 await lab.getByLabel('Value B').fill('1.2')
 await lab.getByRole('button',{name:'RUN 100 SEEDS FOR EACH VALUE'}).click()
 await expect(lab.getByText('CONTROLLED STUDY COMPLETE')).toBeVisible({timeout:75000})
 await expect(page.getByRole('button',{name:'Play',exact:true})).toBeVisible()
 const downloadPromise=page.waitForEvent('download')
 await lab.getByRole('button',{name:'JSON',exact:true}).click()
 const download=await downloadPromise
 const stream=await download.createReadStream()
 let raw='';for await(const chunk of stream)raw+=chunk.toString()
 const data=JSON.parse(raw)
 expect(data.config).toMatchObject({variable:'temperature',valueA:0.4,valueB:1.2,count:100,duration:20,arrangement:'fixed',initialSeed:42,seedSelection:'random'})
 expect(data.config.seeds).toHaveLength(100)
 expect(new Set(data.config.seeds).size).toBe(100)
 expect(data.config.seeds.every((seed:number)=>seed>=1&&seed<=4294967295)).toBe(true)
 expect(data.version).toBe(2)
 expect(data.results).toHaveLength(200)
 expect(new Set(data.results.map((r:{seed:number})=>r.seed)).size).toBe(100)
 for(let i=0;i<200;i+=2){const seed=data.config.seeds[i/2];expect(data.results[i]).toMatchObject({variant:'A',seed,initialSeed:42});expect(data.results[i+1]).toMatchObject({variant:'B',seed,initialSeed:42})}
 const a=data.results.filter((r:{variant:string;firstSuccess:number|null})=>r.variant==='A'&&r.firstSuccess!==null).length
 const b=data.results.filter((r:{variant:string;firstSuccess:number|null})=>r.variant==='B'&&r.firstSuccess!==null).length
 await expect(lab.locator('.controlled-card').nth(0).locator('.controlled-score')).toContainText(String(a))
 await expect(lab.locator('.controlled-card').nth(1).locator('.controlled-score')).toContainText(String(b))
 expect(data.uncertainty.difference.difference).toBeCloseTo((b-a)/100)
 expect(data.uncertainty.rateA.low).toBeLessThanOrEqual(a/100)
 expect(data.uncertainty.rateA.high).toBeGreaterThanOrEqual(a/100)
 await expect(lab.getByText(/Conservative 95% range for the paired difference/)).toBeVisible()
 await lab.getByRole('button',{name:'REPEAT THESE SEEDS'}).click()
 await expect(lab.getByText('CONTROLLED STUDY COMPLETE')).toBeVisible({timeout:75000})
 const againPromise=page.waitForEvent('download')
 await lab.getByRole('button',{name:'JSON',exact:true}).click()
 const againStream=await (await againPromise).createReadStream()
 let againRaw='';for await(const chunk of againStream)againRaw+=chunk.toString()
 const again=JSON.parse(againRaw)
 expect(again.config.seeds).toEqual(data.config.seeds)
 expect(again.results).toEqual(data.results)
 console.log(`Controlled study replayed: A ${a}/100, B ${b}/100`)
})

