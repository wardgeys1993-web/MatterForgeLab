import {_electron as electron,expect} from '@playwright/test'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import assert from 'node:assert/strict'
const profile=await fs.mkdtemp(path.join(os.tmpdir(),'matterforge-desktop-qa-'))
const output=path.resolve('.Codex/desktop-qa');await fs.mkdir(output,{recursive:true})
const executablePath=process.env.MATTERFORGE_TEST_EXE||path.resolve('release/win-unpacked/MatterForge Lab.exe')
const env={...process.env};delete env.ELECTRON_RUN_AS_NODE
const errors=[],requests=[],checks=[]
let application
const launch=()=>electron.launch({executablePath,args:[`--user-data-dir=${profile}`],env,timeout:30000})
try{
 application=await launch()
 let page=await application.firstWindow()
 page.on('pageerror',error=>errors.push(error.message))
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
 page.on('request',request=>{if(/^https?:/.test(request.url()))requests.push(request.url())})
 await expect(page.getByRole('heading',{name:/Big discoveries/})).toBeVisible()
 await page.evaluate(()=>document.fonts.ready)
 await expect(page.locator('.hero h1')).toHaveCSS('opacity','1')
 await expect(page.locator('.hero .primary')).toHaveCSS('opacity','1')
 const version=await application.evaluate(({app})=>app.getVersion())
 assert.equal(await page.evaluate(()=>typeof window.require),'undefined')
 assert.equal(await page.evaluate(()=>typeof window.process),'undefined')
 const preferences=await application.evaluate(({BrowserWindow})=>{const p=BrowserWindow.getAllWindows()[0].webContents.getLastWebPreferences();return {sandbox:p.sandbox,contextIsolation:p.contextIsolation,nodeIntegration:p.nodeIntegration,webSecurity:p.webSecurity}})
 assert.deepEqual(preferences,{sandbox:true,contextIsolation:true,nodeIntegration:false,webSecurity:true})
 checks.push('Packaged executable launches with sandbox, context isolation and no Node access in the renderer.')
 await page.screenshot({path:path.join(output,'discovery.png')})
 await page.getByRole('button',{name:'App updates',exact:true}).click()
 await expect(page.getByRole('dialog')).toContainText(version)
 await expect(page.getByRole('button',{name:'CHECK FOR UPDATES',exact:true})).toBeEnabled()
 await page.screenshot({path:path.join(output,'updates.png')})
 await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible()
 checks.push('Update dialog displays the real version and supports keyboard dismissal.')
 await page.getByRole('button',{name:'START MY FIRST EXPERIMENT'}).click()
 await page.getByRole('button',{name:'Pause',exact:true}).click()
 await page.getByRole('button',{name:'SAVE AS A'}).click()
 const saved=await page.evaluate(()=>localStorage.getItem('matterforge-saved'))
 assert(saved)
 await page.getByRole('button',{name:'RESTORE A'}).click()
 await expect(page.getByText('Experiment restored and paused.')).toBeVisible()
 await page.screenshot({path:path.join(output,'chamber.png')})
 await page.evaluate(()=>window.dispatchEvent(new Event('matterforge-save-now')))
 const chamber=await page.evaluate(()=>localStorage.getItem('matterforge-desktop-chamber'))
 assert(chamber)
 checks.push('Simulation runs, pauses, saves and restores experiment A; chamber autosave records the exact state.')
 await page.getByRole('button',{name:'Research lab',exact:true}).click()
 await page.getByLabel('Research candidates').selectOption('4')
 await page.getByLabel('Research discovery seeds').selectOption('4')
 await page.getByLabel('Research confirmation seeds').selectOption('4')
 await page.getByLabel('Research duration').selectOption('20')
 await page.getByRole('button',{name:'START RESEARCH'}).click()
 await expect(page.getByRole('heading',{name:'Research complete'})).toBeVisible({timeout:90000})
 await expect(page.getByText('Independent confirmation',{exact:true})).toBeVisible()
 await page.screenshot({path:path.join(output,'research.png')})
 checks.push('Packaged research worker completes discovery and independent confirmation with real simulation trials.')
 await page.getByRole('button',{name:'Learning library',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Learn the language of matter.'})).toBeVisible()
 await page.getByRole('button',{name:'Manufacturing ladder',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Shape and qualify materials'})).toBeVisible()
 checks.push('Learning library and manufacturing ladder render in the native app.')
 assert.deepEqual(requests,[],'The lab must not make automatic external requests.')
 assert.deepEqual(errors,[])
 await application.close();application=null
 application=await launch();page=await application.firstWindow()
 await expect(page.getByRole('heading',{name:/Big discoveries/})).toBeVisible()
 assert.equal(await page.evaluate(()=>localStorage.getItem('matterforge-saved')),saved)
 assert.equal(await page.evaluate(()=>localStorage.getItem('matterforge-desktop-chamber')),chamber)
 await page.getByRole('button',{name:'Research lab',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Research complete'})).toBeVisible()
 checks.push('A second native launch preserves experiment A, the current chamber and completed research.')
 if(process.env.MATTERFORGE_TEST_LIVE_UPDATE==='1'){
  await page.getByRole('button',{name:'App updates',exact:true}).click()
  await page.getByRole('button',{name:'CHECK FOR UPDATES',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('latest stable release',{timeout:45000})
  checks.push('Live GitHub update check confirms the installed version is current.')
 }
 await fs.writeFile(path.join(output,'verification.json'),JSON.stringify({version,checks,errors,externalRequests:requests},null,2)+'\n')
 console.log(JSON.stringify({version,checks},null,2))
}catch(error){if(application){const pages=application.context().pages();if(pages[0]){await pages[0].screenshot({path:path.join(output,'failure.png')}).catch(()=>{});console.error((await pages[0].locator('body').innerText().catch(()=>'' )).slice(0,1800))}}console.error({errors,requests});throw error}
finally{if(application)await application.close();await fs.rm(profile,{recursive:true,force:true,maxRetries:5,retryDelay:250})}
